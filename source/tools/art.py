# boss: "The Smudge", a 32x32 ink mass with a face, generated procedurally so the
# outline is clean. Three frames: idle A, idle B (mouth narrower), hurt (eyes crossed).
def _boss(frame):
    """The Smudge, 32x32, drawn with OBP1: body colour 1 (dark grey when solid, pale when ghosted), outline and
    pupils colour 3. Eyes and mouth are transparent holes (colour 0), so the face reads in BOTH palettes: the
    ghost palette flattens every opaque shade to pale grey, but holes always show the paper behind the boss.
    frame 0/1: idle wobble (arms and drips move, pupils glance); frame 2: hurt (crossed eyes, round mouth)."""
    W = H = 32
    import math
    mask = [[False] * W for _ in range(H)]

    def blob(cx, cy, rx, ry):
        for y in range(H):
            for x in range(W):
                dx = (x + 0.5 - cx) / rx
                dy = (y + 0.5 - cy) / ry
                if dx * dx + dy * dy <= 1.0:
                    mask[y][x] = True

    blob(16, 14, 12.5, 10.5)                      # head-heavy body
    blob(11, 5, 5.5, 3.5)                         # cowlick lump on top
    blob(21, 6, 3.5, 2.5)
    arm_y = 17 if frame != 1 else 13              # stubby arms, raised on frame 1
    blob(3.5, arm_y, 4.0, 2.6); blob(28.5, arm_y, 4.0, 2.6)
    for (cx, length) in ((8, 4), (15, 7), (22, 3)):   # drips below the body
        for yy in range(23, min(H, 24 + length + (frame % 2))):
            for xx in (cx, cx + 1):
                mask[yy][xx] = True
    g = [[0] * W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            if not mask[y][x]:
                continue
            edge = False
            for ddx, ddy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + ddx, y + ddy
                if nx < 0 or ny < 0 or nx >= W or ny >= H or not mask[ny][nx]:
                    edge = True
            g[y][x] = 3 if edge else 1

    def rect(x0, y0, x1, y1, v):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                g[y][x] = v

    # darker ink pooling inside the smudge (colour 3 blotches)
    rect(20, 9, 23, 10, 3); rect(22, 11, 24, 12, 3); rect(6, 18, 7, 19, 3); rect(13, 4, 14, 4, 3)
    if frame < 2:
        for ex in (8, 19):                        # eye holes with pupils that glance left/right
            rect(ex, 8, ex + 4, 12, 0)
            pxp = ex + 1 + frame
            rect(pxp, 9 + frame, pxp + 1, 10 + frame, 3)
        rect(10, 16, 21, 18, 0)                   # grin: a wide hole with teeth hanging from the top edge
        for tx in (12, 16, 20):
            g[16][tx] = 1
        rect(11, 19, 13, 19, 0); rect(18, 19, 20, 19, 0)   # jagged lower lip
    else:
        for ex in (8, 19):                        # hurt: crossed-out eyes (transparent X) and a round mouth
            for i in range(5):
                g[8 + i][ex + i] = 0; g[8 + i][ex + 4 - i] = 0
        rect(14, 16, 17, 19, 0); g[16][14] = 1; g[16][17] = 1; g[19][14] = 1; g[19][17] = 1
    return '\n'.join(''.join('.-+#'[v] for v in row) for row in g)

