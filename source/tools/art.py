GFX_BOSS_SPRITE_BASE = 208   # OBJ tiles 208..255 (aliases BG 208..255, which no boss-plate backdrop uses)


def build(outdir):
    os.makedirs(outdir, exist_ok=True)
    # ---------------- BG world tiles -------------------------------------
    bg_tiles = []          # list of 16-byte tiles
    bg_index = {}          # bytes -> index
    meta_tiles = []        # per metatile: (tl,tr,bl,br)

    def add_bg(t):
        b = tile_bytes(t)
        if b in bg_index:
            return bg_index[b]
        idx = len(bg_tiles)
        bg_index[b] = idx
        bg_tiles.append(b)
        return idx

    add_bg([[0] * 8 for _ in range(8)])  # tile 0 = empty

    # Backdrop tiles share the title logo's BG slots 192..255 (the title reloads the logo, every plate reloads
    # the backdrop). On the DMG, BG tiles 128..255 and OBJ tiles 128..255 are the same VRAM (0x8800..0x8FFF),
    # and the boss's 48 sprite tiles live at OBJ 208..255 on the last plate. So the backdrop metatiles used on
    # the boss plate are allocated first, into 192..207 (never aliased by the boss), the rest go to 208..253,
    # and any overflow goes into the world region's free slots (<128). An all-paper subtile is tile 0.
    BD_BOSS_SAFE_MAX = GFX_BOSS_SPRITE_BASE - 192
    bd_tiles = []
    bd_index = {}

    def add_bd(t):
        b = tile_bytes(t)
        if b == bytes(16):
            return 0
        if b in bd_index:
            return bd_index[b]
        if b in bg_index:
            return bg_index[b]
        if len(bd_tiles) >= 62:
            return add_bg(t)                  # overflow into free world slots
        idx = 192 + len(bd_tiles)
        bd_index[b] = idx
        bd_tiles.append(b)
        return idx

    bd_names = [n for n in META_ORDER if n.startswith('BD_')]
    boss_first = [n for n in bd_names if n in _bd.BOSS_PLATE_NAMES] + [n for n in bd_names if n not in _bd.BOSS_PLATE_NAMES]
    bd_meta = {}
    for name in boss_first:
        g = grid(META[name])
        check(g, 16, 16, name)
        assert all(v in (0, 2) for row in g for v in row), f'{name}: backdrops use colour 2 only'
        bd_meta[name] = (add_bd(sub(g, 0, 0)), add_bd(sub(g, 8, 0)), add_bd(sub(g, 0, 8)), add_bd(sub(g, 8, 8)))
        if name in _bd.BOSS_PLATE_NAMES:
            assert all(i < GFX_BOSS_SPRITE_BASE for i in bd_meta[name]), f'{name}: boss-plate backdrop tile aliases boss sprites'
    for name in META_ORDER:
        if name.startswith('BD_'):
            meta_tiles.append(bd_meta[name])
            continue
        g = grid(META[name])
        check(g, 16, 16, name)
        tl = add_bg(sub(g, 0, 0)); tr = add_bg(sub(g, 8, 0))
        bl = add_bg(sub(g, 0, 8)); br = add_bg(sub(g, 8, 8))
        meta_tiles.append((tl, tr, bl, br))
    n_world = len(bg_tiles)
    assert n_world <= 128, f'world tiles {n_world} > 128'
    assert 192 + len(bd_tiles) <= 254, f'backdrop tiles {len(bd_tiles)} overflow'

    # ---------------- font + HUD at BG 128.. ------------------------------
    font_tiles = []
    font_map = {}
    for ch in FONT_CHARS:
        font_map[ch] = 128 + len(font_tiles)
        font_tiles.append(tile_bytes(font_tile(ch)))
    hud_base = 128 + len(font_tiles)
    hud_map = {}
    for name in HUD_ORDER:
        hud_map[name] = hud_base + len(font_tiles) - len(FONT_CHARS) + 0 if False else 128 + len(font_tiles)
        font_tiles.append(tile_bytes(HUD[name]))
    assert 128 + len(font_tiles) <= 192, 'font/HUD overflow'

    # ---------------- tile class table (256 entries) ---------------------
    tile_class = [0] * 256
    for mi, name in enumerate(META_ORDER):
        cls = META_CLASS[name]
        for q, idx in enumerate(meta_tiles[mi]):
            if idx == 0:
                continue
            if tile_class[idx] not in (0, cls[q]):
                raise SystemExit(f'tile {idx} shared with different class ({name})')
            tile_class[idx] = cls[q]

    # ---------------- sprites --------------------------------------------
    spr_tiles = []  # indices 0..

    def add_spr16(name):
        g = grid(SPR[name]); check(g, 16, 16, name)
        base = len(spr_tiles)
        for col in (0, 8):
            spr_tiles.append(tile_bytes(sub(g, col, 0)))
            spr_tiles.append(tile_bytes(sub(g, col, 8)))
        return base

    def add_spr8x16(name):
        g = grid(SPR[name]); check(g, 8, 16, name)
        base = len(spr_tiles)
        spr_tiles.append(tile_bytes(sub(g, 0, 0)))
        spr_tiles.append(tile_bytes(sub(g, 0, 8)))
        return base

    spr_base = {}
    for name in SPR_ORDER:
        spr_base[name] = add_spr16(name)
    for name in SPR_8x16_ORDER:
        spr_base[name] = add_spr8x16(name)
    while len(spr_tiles) % 4:
        spr_tiles.append(bytes(16))
    for name in SPR_EXTRA16:
        spr_base[name] = add_spr16(name)
    n_spr_main = len(spr_tiles)
    assert n_spr_main <= 128, f'sprite tiles {n_spr_main} > 128'

    # boss frames at OBJ 192.. (32x32 -> 4 columns of 8x16 x 2 rows = 8 OAM entries, 16 tiles)
    boss_tiles = []
    boss_frames = []
    for bg_ in (BOSS0, BOSS1, BOSS_HURT):
        g = grid(bg_); check(g, 32, 32, 'boss')
        base = GFX_BOSS_SPRITE_BASE + len(boss_tiles)
        boss_frames.append(base)
        for row in (0, 16):
            for col in (0, 8, 16, 24):
                boss_tiles.append(tile_bytes(sub(g, col, row)))
                boss_tiles.append(tile_bytes(sub(g, col, row + 8)))
    assert GFX_BOSS_SPRITE_BASE + len(boss_tiles) <= 256

    # ---------------- title logo tiles (own tileset, loaded on title) -----
    logo_tiles = []
    logo_map = []  # per letter: 2x3 tile indices
    for ch in 'HALFTONE':
        g = halftone(grid(LOGO[ch]))
        check(g, 16, 24, ch)
        idxs = []
        for ty in range(3):
            for tx in range(2):
                logo_tiles.append(tile_bytes(sub(g, tx * 8, ty * 8)))
                idxs.append(len(logo_tiles) - 1)
        logo_map.append(idxs)

    # ---------------- write C ---------------------------------------------
    c = ['/* Generated by tools/art.py - original HALFTONE art. Do not edit by hand. */',
         '#include <stdint.h>', '#pragma bank 2', '']
    c.append(c_array('gfx_world_tiles', b''.join(bg_tiles)))
    c.append(c_array('gfx_font_tiles', b''.join(font_tiles)))
    c.append(c_array('gfx_sprite_tiles', b''.join(spr_tiles)))
    c.append(c_array('gfx_boss_tiles', b''.join(boss_tiles)))
    c.append(c_array('gfx_logo_tiles', b''.join(logo_tiles)))
    c.append(c_array('gfx_backdrop_tiles', b''.join(bd_tiles)))
    meta_flat = bytes(b for m in meta_tiles for b in m)
    c.append(c_array('gfx_meta_tiles', meta_flat))
    c.append(c_array('gfx_tile_class', bytes(tile_class)))
    with open(os.path.join(outdir, 'gfx.c'), 'w') as f:
        f.write('\n'.join(c))

    h = ['/* Generated by tools/art.py */', '#ifndef GFX_H', '#define GFX_H', '#include <stdint.h>',
         f'#define GFX_WORLD_TILE_COUNT {len(bg_tiles)}',
         f'#define GFX_FONT_TILE_COUNT {len(font_tiles)}',
         f'#define GFX_FONT_BASE 128',
         f'#define GFX_SPRITE_TILE_COUNT {len(spr_tiles)}',
         f'#define GFX_BOSS_TILE_COUNT {len(boss_tiles)}',
         f'#define GFX_BOSS_TILE_BASE {GFX_BOSS_SPRITE_BASE}',
         f'#define GFX_LOGO_TILE_COUNT {len(logo_tiles)}',
         f'#define GFX_BACKDROP_TILE_COUNT {len(bd_tiles)}',
         f'#define GFX_BACKDROP_TILE_BASE 192',
         f'#define META_COUNT {len(META_ORDER)}']
    for i, name in enumerate(META_ORDER):
        h.append(f'#define MT_{name} {i}')
    for name, idx in spr_base.items():
        h.append(f'#define SPR_{name} {idx}')
    for i, b in enumerate(boss_frames):
        h.append(f'#define SPR_BOSS{i} {b}')
    for name in HUD_ORDER:
        h.append(f'#define T_HUD_{name} {hud_map[name]}')
