# TITLE LOGO: "HALFTONE" letters in a 16x24 cell (14 px glyph + 2 px gap),
# geometric sans with 3 px strokes, finished with a letterpress halftone screen.
# --------------------------------------------------------------------------
def _rects_to_grid(rects, cuts=()):
    g = [[0] * 16 for _ in range(24)]
    for (x, y, w, h) in rects:
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                g[yy][xx] = 3
    for (x, y) in cuts:
        g[y][x] = 0
    return g


def _letter_N():
    g = _rects_to_grid([(0, 0, 3, 24), (11, 0, 3, 24)])
    for y in range(24):
        x = 3 + (y * 8) // 24
        for xx in range(x, min(x + 3, 14)):
            g[y][xx] = 3
    return g


def _letter_O():
    cuts = [(0, 0), (1, 0), (0, 1), (13, 0), (12, 0), (13, 1), (0, 23), (1, 23), (0, 22), (13, 23), (12, 23), (13, 22),
            (3, 3), (10, 3), (3, 20), (10, 20)]
    g = _rects_to_grid([(0, 0, 14, 24)])
    for y in range(3, 21):
        for x in range(3, 11):
            g[y][x] = 0
    for (x, y) in cuts:
        g[y][x] = 0 if g[y][x] == 3 and (x in (0, 1, 12, 13)) else g[y][x]
    for (x, y) in [(3, 3), (10, 3), (3, 20), (10, 20)]:
        g[y][x] = 3
    return g


