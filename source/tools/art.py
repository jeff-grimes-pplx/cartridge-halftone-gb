    write_png(os.path.join(outdir, 'preview_sprites.png'), pix, 10, sp)
    for bname, bg_ in (('boss0', BOSS0), ('boss1', BOSS1), ('boss_hurt', BOSS_HURT)):
        write_png(os.path.join(outdir, f'preview_{bname}.png'), grid(bg_), 8, sp)
    # metatile preview sheet
