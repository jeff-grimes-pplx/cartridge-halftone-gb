def font_tile(ch):
    rows = FONT_THIN[ch]
    t = []
    for r in range(8):
        if r < 7:
            bits = [int(b) for b in rows[r]]
            # dilate right by one pixel -> bold 6px glyph, left aligned at x=1
            out = [0] * 8
            for x in range(5):
                if bits[x]:
                    out[x + 1] = 2
                    out[x + 2] = 2
            t.append(out)
        else:
            t.append([0] * 8)
    return t


