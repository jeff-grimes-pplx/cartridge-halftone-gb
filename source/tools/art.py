    tiles_sheet(bg_tiles, 16, os.path.join(outdir, 'preview_world_tiles.png'))
    tiles_sheet(font_tiles, 16, os.path.join(outdir, 'preview_font.png'))
    tiles_sheet(bd_tiles, 16, os.path.join(outdir, 'preview_backdrop_tiles.png'))
    # sprites preview with sprite palette (1->white)
    sp = [(0xF4, 0xF1, 0xE6), (0xFF, 0xFF, 0xFF), (0x56, 0x55, 0x50), (0x12, 0x12, 0x12)]
    # draw each 16x16 frame
    frames = SPR_ORDER + SPR_EXTRA16
    W = 16 * len(frames)
