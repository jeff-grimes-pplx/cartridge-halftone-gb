def halftone(letter_grid, phase=0):
    """Letterpress duotone: solid black top, dark-grey lower third carrying a regular
    diagonal screen of paper-coloured dots that opens up toward the baseline."""
    out = []
    for y, row in enumerate(letter_grid):
        new = []
        for x, v in enumerate(row):
            if v != 3:
                new.append(v)
                continue
            if y < 14:
                new.append(3)
            elif y == 14:
                new.append(3 if (x & 1) == 0 else 2)
            else:
                val = 2
                ry = y - 15
                if ry >= 1 and (ry & 1) == 1:
                    off = 2 if ((ry >> 1) & 1) else 0
                    if (x + off) % 4 == 0:
                        val = 0
                    if ry >= 5 and (x + off) % 4 == 1:
                        val = 0
                new.append(val)
        out.append(new)
    return out


